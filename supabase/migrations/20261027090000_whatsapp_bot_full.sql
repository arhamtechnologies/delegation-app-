-- WhatsApp bot, full app coverage.
-- Human-friendly references: checklist items show as C<n>, recurring checklist templates as R<n>.
alter table public.checklist_items add column if not exists short_code bigint generated by default as identity unique;
alter table public.checklist_templates add column if not exists short_code bigint generated by default as identity unique;

-- Claude usage per bot reply; null means the reply needed no model call.
alter table public.wa_messages add column if not exists model text;
alter table public.wa_messages add column if not exists input_tokens integer;
alter table public.wa_messages add column if not exists output_tokens integer;
alter table public.wa_messages add column if not exists cache_read_tokens integer;
alter table public.wa_messages add column if not exists cache_write_tokens integer;

-- The bot reads the MIS report with the service-role client.
grant execute on function public.get_work_report(text, text, date, date, text, text, uuid) to service_role;
