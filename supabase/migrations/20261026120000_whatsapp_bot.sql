-- WhatsApp control channel (Green API). New tables are service-role only: RLS on, no policies.
alter table public.employees add column if not exists whatsapp_chat_id text unique;

-- Human-friendly task number shown as #N; identity backfills existing rows.
alter table public.tasks add column if not exists short_code bigint generated by default as identity unique;

create table if not exists public.wa_messages(
  id uuid primary key default gen_random_uuid(),
  wa_message_id text unique,
  chat_id text not null,
  sender text,
  direction text not null check (direction in ('in','out')),
  body text,
  created_at timestamptz not null default now()
);
create index if not exists wa_messages_chat_created_idx on public.wa_messages(chat_id, created_at desc);

create table if not exists public.wa_pending_actions(
  id uuid primary key default gen_random_uuid(),
  chat_id text not null,
  actor_employee_id uuid not null references public.employees(id) on delete cascade,
  actions jsonb not null,
  status text not null default 'pending' check (status in ('pending','confirmed','cancelled','expired')),
  expires_at timestamptz not null default now() + interval '10 minutes',
  handled_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists wa_pending_actions_chat_status_idx on public.wa_pending_actions(chat_id, status, expires_at desc);
create index if not exists wa_pending_actions_actor_idx on public.wa_pending_actions(actor_employee_id);

alter table public.wa_messages enable row level security;
alter table public.wa_pending_actions enable row level security;
